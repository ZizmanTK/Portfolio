/**
 * Writes src/styles/_skill-icons.scss from src/content/skill-icons.json: one `.si-<slug>` class per skill, whose
 * single-colour icon is a CSS mask (`--icon`) and whose brand colour (`--c`) shows on hover in the résumé view; and
 * src/app/core/skill-icons.ts, the names that have an icon (so the app bundle does not carry the drawings).
 * Run it after adding a skill icon:  npm run icons
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { icons } = JSON.parse(readFileSync(join(root, 'src/content/skill-icons.json'), 'utf8'));

/** Same slugs as src/app/core/content.ts → skillSlug(). */
const slug = (n) => ({ 'C#': 'csharp', 'C++': 'cpp', '.NET': 'dotnet', C: 'c' })[n] || n.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

let css = '/* Generated by scripts/build-icon-styles.mjs from src/content/skill-icons.json (Simple Icons CC0, Devicon MIT, Lucide ISC). Do not edit. */\n';
for (const [name, { mask, hex }] of Object.entries(icons)) css += `.si-${slug(name)}{--icon:url("${mask}");--c:${hex}}\n`;
writeFileSync(join(root, 'src/styles/_skill-icons.scss'), css);
const names = Object.keys(icons).map((n) => `  ${JSON.stringify(n)},`).join('\n');
const ts = [
  '// Generated by scripts/build-icon-styles.mjs from src/content/skill-icons.json. Do not edit.',
  '/** The skills that have an icon (a .si-<slug> class in src/styles/_skill-icons.scss). */',
  'export const SKILLS_WITH_ICONS = new Set([',
  names,
  ']);',
  '',
].join('\n');
writeFileSync(join(root, 'src/app/core/skill-icons.ts'), ts);
console.log(`${Object.keys(icons).length} icons → src/styles/_skill-icons.scss, src/app/core/skill-icons.ts`);
